package com.joyong.ytsaver

import com.google.mlkit.common.model.DownloadConditions
import com.google.mlkit.nl.translate.TranslateLanguage
import com.google.mlkit.nl.translate.Translation
import com.google.mlkit.nl.translate.TranslatorOptions
import kotlinx.coroutines.ensureActive
import kotlinx.coroutines.tasks.await
import okhttp3.Request
import org.json.JSONObject
import java.io.File
import java.io.IOException
import kotlin.coroutines.coroutineContext

/**
 * 유튜브 자막을 받아 한국어 자막 파일(WebVTT)로 저장한다.
 * 1) 한국어 자막이 있으면 그대로
 * 2) 없으면 유튜브 자동 번역(tlang=ko)
 * 3) 그것도 막히면 ML Kit으로 기기 안에서 번역
 */
object SubtitleSaver {

    data class Cue(val startMs: Long, val endMs: Long, val text: String)

    data class Result(val ko: File?, val orig: File?, val origLang: String)

    private val HANGUL = Regex("[가-힣]")

    suspend fun save(
        dir: File,
        tracks: List<Caption>,
        title: String,
        onStatus: (String) -> Unit,
    ): Result {
        val korean = tracks.filter { it.isKorean() }
            .sortedBy { it.isAutoGenerated }.firstOrNull()
        val source = pickSource(tracks.filterNot { it.isKorean() })

        var origFile: File? = null
        var sourceCues: List<Cue>? = null
        if (source != null) {
            onStatus("원어 자막 받는 중…")
            sourceCues = runCatching { fetch(source.url, null) }.getOrNull()
                ?.takeIf { it.isNotEmpty() }
            if (sourceCues != null) {
                origFile = File(dir, "sub_orig.vtt").also { writeVtt(it, sourceCues) }
            }
        }

        val koCues: List<Cue>? = when {
            korean != null -> {
                onStatus("한국어 자막 받는 중…")
                runCatching { fetch(korean.url, null) }.getOrNull()
            }
            source != null -> {
                // 1) Claude 설정이 있으면 가장 자연스러운 AI 번역 2) 유튜브 자동 번역 3) 기기 번역
                sourceCues?.let { translateWithAi(it, source.languageTag, title, onStatus) }
                    ?: run {
                        onStatus("한국어로 자동 번역 중…")
                        null
                    }
                    ?: runCatching { fetch(source.url, "ko") }.getOrNull()
                    ?.takeIf { cues -> cues.any { HANGUL.containsMatchIn(it.text) } }
                    ?: sourceCues?.let { translateOnDevice(it, source.languageTag, onStatus) }
            }
            else -> null
        }?.takeIf { it.isNotEmpty() }

        val koFile = koCues?.let { File(dir, "sub_ko.vtt").also { f -> writeVtt(f, it) } }
        return Result(koFile, origFile, if (origFile != null) source!!.languageTag else "")
    }

    /** Claude로 번역. 설정이 없거나 실패하면 null (다음 방법으로 넘어감) */
    private suspend fun translateWithAi(
        cues: List<Cue>,
        languageTag: String,
        title: String,
        onStatus: (String) -> Unit,
    ): List<Cue>? {
        val context = App.instance
        if (!AiSettings.isReady(context)) return null
        return try {
            ClaudeTranslator.translate(context, cues, languageTag, title, onStatus)
        } catch (e: Exception) {
            if (e is kotlinx.coroutines.CancellationException) throw e
            lastAiError = e.message ?: e.javaClass.simpleName
            null
        }
    }

    /** 마지막 AI 번역 실패 사유 (자막만 다시 번역할 때 안내용) */
    @Volatile
    var lastAiError: String? = null

    /**
     * 이미 저장된 원어 자막(sub_orig.vtt)을 Claude로 다시 번역한다.
     * 유튜브에 다시 접속하지 않으므로 유튜브가 막혀 있어도 된다.
     */
    suspend fun retranslateWithAi(video: SavedVideo, onStatus: (String) -> Unit): File {
        val orig = video.subOrig ?: throw SaveException("저장된 원어 자막이 없어요")
        val cues = readVtt(orig)
        if (cues.isEmpty()) throw SaveException("원어 자막이 비어 있어요")
        val translated = ClaudeTranslator.translate(
            App.instance, cues, video.subOrigLang, video.title, onStatus
        )
        return File(video.dir, "sub_ko.vtt").also { writeVtt(it, translated) }
    }

    /** writeVtt로 쓴 파일을 다시 읽는다 */
    private fun readVtt(file: File): List<Cue> {
        val blocks = file.readText().replace("\r\n", "\n").split(Regex("\n{2,}"))
        return blocks.mapNotNull { block ->
            val lines = block.trim().lines()
            val timing = lines.indexOfFirst { "-->" in it }
            if (timing < 0) return@mapNotNull null
            val (start, end) = lines[timing].split("-->").map { parseTime(it.trim()) }
            val text = lines.drop(timing + 1).joinToString("\n")
                .replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")
            if (text.isBlank()) null else Cue(start, end, text)
        }
    }

    private fun parseTime(s: String): Long {
        val parts = s.substringBefore(' ').split(':')
        val sec = parts.last().split('.')
        val h = if (parts.size == 3) parts[0].toLong() else 0
        val m = parts[parts.size - 2].toLong()
        return ((h * 60 + m) * 60 + sec[0].toLong()) * 1000 + (sec.getOrNull(1)?.padEnd(3, '0')?.take(3)?.toLong() ?: 0)
    }

    private fun Caption.isKorean() = languageTag.lowercase().startsWith("ko")

    /** 사람이 단 자막을 우선, 그중에서도 자동 생성 자막(=영상 원어)과 같은 언어를 우선 */
    private fun pickSource(tracks: List<Caption>): Caption? {
        val auto = tracks.firstOrNull { it.isAutoGenerated }
        val manual = tracks.filter { !it.isAutoGenerated }
        val originalLang = auto?.languageTag?.substringBefore('-')
        return manual.firstOrNull { it.languageTag.substringBefore('-') == originalLang }
            ?: manual.firstOrNull()
            ?: auto
    }

    /** json3 형식으로 받아 큐 목록으로 바꾼다. tlang을 주면 유튜브가 번역해서 돌려준다. */
    private suspend fun fetch(baseUrl: String, translateTo: String?): List<Cue> {
        coroutineContext.ensureActive()
        val url = baseUrl.replace(Regex("&fmt=[^&]*"), "")
            .replace(Regex("&tlang=[^&]*"), "") +
            "&fmt=json3" + (translateTo?.let { "&tlang=$it" } ?: "")
        val request = Request.Builder().url(url).header("User-Agent", NetDownloader.USER_AGENT).build()
        val body = App.http.newCall(request).execute().use { resp ->
            if (!resp.isSuccessful) throw IOException("HTTP ${resp.code}")
            resp.body?.string().orEmpty()
        }
        if (body.isBlank()) throw IOException("빈 자막")
        return parseJson3(body)
    }

    private fun parseJson3(body: String): List<Cue> {
        val events = JSONObject(body).optJSONArray("events") ?: return emptyList()
        val raw = ArrayList<Cue>()
        for (i in 0 until events.length()) {
            val e = events.optJSONObject(i) ?: continue
            val segs = e.optJSONArray("segs") ?: continue
            val text = buildString {
                for (j in 0 until segs.length()) append(segs.optJSONObject(j)?.optString("utf8").orEmpty())
            }.replace("​", "").trim()
            if (text.isEmpty()) continue
            val start = e.optLong("tStartMs")
            val dur = e.optLong("dDurationMs").takeIf { it > 0 } ?: 2000L
            raw += Cue(start, start + dur, text)
        }
        raw.sortBy { it.startMs }
        // 자동 생성 자막은 줄이 겹쳐서 올라오므로 다음 줄이 시작하면 앞 줄을 끝낸다
        return raw.mapIndexed { i, cue ->
            val next = raw.getOrNull(i + 1)?.startMs
            if (next != null && next > cue.startMs && next < cue.endMs) cue.copy(endMs = next) else cue
        }
    }

    private suspend fun translateOnDevice(
        cues: List<Cue>,
        languageTag: String,
        onStatus: (String) -> Unit,
    ): List<Cue>? {
        val source = TranslateLanguage.fromLanguageTag(languageTag.substringBefore('-').lowercase())
            ?: return null
        if (source == TranslateLanguage.KOREAN) return cues
        val translator = Translation.getClient(
            TranslatorOptions.Builder()
                .setSourceLanguage(source)
                .setTargetLanguage(TranslateLanguage.KOREAN)
                .build()
        )
        return try {
            onStatus("번역 모델 받는 중… (처음 한 번만)")
            translator.downloadModelIfNeeded(DownloadConditions.Builder().build()).await()
            cues.mapIndexed { i, cue ->
                coroutineContext.ensureActive()
                if (i % 20 == 0) onStatus("기기에서 번역 중… ${i * 100 / cues.size}%")
                cue.copy(text = translator.translate(cue.text).await())
            }
        } catch (e: Exception) {
            if (e is kotlinx.coroutines.CancellationException) throw e
            null
        } finally {
            translator.close()
        }
    }

    private fun writeVtt(file: File, cues: List<Cue>) {
        file.bufferedWriter().use { w ->
            w.write("WEBVTT\n\n")
            for (cue in cues) {
                w.write("${time(cue.startMs)} --> ${time(cue.endMs)}\n")
                w.write(cue.text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))
                w.write("\n\n")
            }
        }
    }

    private fun time(ms: Long) = String.format(
        "%02d:%02d:%02d.%03d", ms / 3_600_000, ms / 60_000 % 60, ms / 1000 % 60, ms % 1000
    )
}
