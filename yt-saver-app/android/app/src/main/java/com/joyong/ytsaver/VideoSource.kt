    /** 유튜브 내부 API(/youtubei/v1/player)에 직접 요청 */
    private object Innertube {
        private const val PLAYER_URL = "https://www.youtube.com/youtubei/v1/player?prettyPrint=false"

        @Volatile
        private var visitorData: String? = null

        private fun visitorData(): String? = visitorData ?: runCatching {
            val web = InnertubeClientRequestInfo.ofWebClient()
            web.clientInfo.clientVersion = YoutubeParsingHelper.getClientVersion()
            YoutubeParsingHelper.getVisitorDataFromInnertube(
                web, NewPipe.getPreferredLocalization(), NewPipe.getPreferredContentCountry(),
                YoutubeParsingHelper.getYouTubeHeaders(), YoutubeParsingHelper.YOUTUBEI_V1_URL,
                null, false
            )
        }.getOrNull()?.also { visitorData = it }

        fun player(id: String, client: Client): VideoInfo {
            val visitor = visitorData()
            val clientJson = JSONObject()
                .put("clientName", client.name)
                .put("clientVersion", client.version)
                .put("hl", "ko")
                .put("gl", "KR")
                .put("userAgent", client.userAgent)
            client.extra.forEach { (k, v) -> clientJson.put(k, v) }
            visitor?.let { clientJson.put("visitorData", it) }

            val playback = JSONObject().put("html5Preference", "HTML5_PREF_WANTS")
            if (client.needsJsPlayer) {
                YoutubeJavaScriptPlayerManager.getSignatureTimestamp(id)?.let {
                    playback.put("signatureTimestamp", it)
                }
            }
            val context = JSONObject().put("client", clientJson)
            client.embedUrl?.let { context.put("thirdParty", JSONObject().put("embedUrl", it)) }
            val body = JSONObject()
                .put("context", context)
                .put("videoId", id)
                .put("playbackContext", JSONObject().put("contentPlaybackContext", playback))
                .put("contentCheckOk", true)
                .put("racyCheckOk", true)

            val request = Request.Builder()
                .url(PLAYER_URL)
                .post(body.toString().toRequestBody("application/json".toMediaType()))
                .header("User-Agent", client.userAgent)
                .header("X-YouTube-Client-Name", client.nameId.toString())
                .header("X-YouTube-Client-Version", client.version)
                .header("Origin", "https://www.youtube.com")
                .apply { visitor?.let { header("X-Goog-Visitor-Id", it) } }
                .apply { client.embedUrl?.let { header("Referer", it) } }
                .build()
            val json = App.http.newCall(request).execute().use { resp ->
                if (!resp.isSuccessful) throw IOException("${client.label}: HTTP ${resp.code}")
                JSONObject(resp.body?.string().orEmpty())
            }

            val playability = json.optJSONObject("playabilityStatus")
            val status = playability?.optString("status").orEmpty()
            if (!status.equals("OK", ignoreCase = true)) {
                val reason = playability?.optString("reason").orEmpty()
                throw IOException("${client.label}: $status \"$reason\"")
            }

            val streaming = json.optJSONObject("streamingData")
                ?: throw IOException("${client.label}: 스트림 정보 없음")
            val streams = buildList {
                parseFormats(id, client, streaming.optJSONArray("formats"), muxed = true, into = this)
                parseFormats(id, client, streaming.optJSONArray("adaptiveFormats"), muxed = false, into = this)
            }
            if (streams.isEmpty()) throw IOException("${client.label}: 받을 수 있는 스트림 없음")

            val details = json.optJSONObject("videoDetails") ?: JSONObject()
            val thumbs = details.optJSONObject("thumbnail")?.optJSONArray("thumbnails")
            val thumb = thumbs?.let { arr ->
                (0 until arr.length()).mapNotNull { arr.optJSONObject(it) }
                    .minByOrNull { kotlin.math.abs(it.optInt("width") - 480) }?.optString("url")
            }
            val captionTracks = json.optJSONObject("captions")
                ?.optJSONObject("playerCaptionsTracklistRenderer")
                ?.optJSONArray("captionTracks")
            val captions = captionTracks?.let { arr ->
                (0 until arr.length()).mapNotNull { arr.optJSONObject(it) }.mapNotNull { t ->
                    val url = t.optString("baseUrl").takeIf { it.isNotEmpty() } ?: return@mapNotNull null
                    Caption(
                        url = url,
                        languageTag = t.optString("languageCode"),
                        isAutoGenerated = t.optString("kind") == "asr" ||
                            t.optString("vssId").startsWith("a."),
                    )
                }
            }.orEmpty()

            return VideoInfo(
                id = id,
                title = details.optString("title").ifEmpty { id },
                uploader = details.optString("author"),
                durationSec = details.optString("lengthSeconds").toLongOrNull() ?: 0,
                thumbnailUrl = thumb,
                streams = streams,
                captions = captions,
                userAgent = client.userAgent,
                via = client.label,
            )
        }

        private fun parseFormats(
            id: String,
            client: Client,
            formats: JSONArray?,
            muxed: Boolean,
            into: MutableList<MediaStream>,
        ) {
            if (formats == null) return
            for (i in 0 until formats.length()) {
                val f = formats.optJSONObject(i) ?: continue
                if (f.has("drmFamilies")) continue
                val url = runCatching { streamUrl(id, client, f) }.getOrNull() ?: continue
                // 예: video/mp4; codecs="avc1.640028"
                val mime = f.optString("mimeType")
                val container = mime.substringBefore(';').trim()
                val codec = mime.substringAfter("codecs=\"", "").substringBefore('"')
                val isAudio = container.startsWith("audio/")
                val kind = when {
                    muxed -> MediaStream.Kind.MUXED
                    isAudio -> MediaStream.Kind.AUDIO
                    else -> MediaStream.Kind.VIDEO_ONLY
                }
                val ext = when (container) {
                    "audio/mp4" -> "m4a"
                    "video/mp4" -> "mp4"
                    "audio/webm", "video/webm" -> "webm"
                    else -> continue
                }
                val track = f.optJSONObject("audioTrack")
                into += MediaStream(
                    url = url,
                    kind = kind,
                    ext = ext,
                    codec = codec,
                    height = f.optInt("height"),
                    bitrate = f.optInt("averageBitrate", f.optInt("bitrate")),
                    contentLength = f.optString("contentLength").toLongOrNull() ?: -1,
                    originalAudio = track == null || track.optBoolean("audioIsDefault", true),
                )
            }
        }

        /** 서명이 걸린 주소는 풀고, 속도 제한(n) 파라미터도 풀어 준다 */
        private fun streamUrl(id: String, client: Client, f: JSONObject): String? {
            var url = f.optString("url").takeIf { it.isNotEmpty() }
            if (url == null) {
                val cipher = f.optString("signatureCipher", f.optString("cipher"))
                if (cipher.isEmpty()) return null
                val params = Uri.parse("?$cipher")
                val base = params.getQueryParameter("url") ?: return null
                val s = params.getQueryParameter("s") ?: return null
                val sp = params.getQueryParameter("sp") ?: "signature"
                url = "$base&$sp=" + YoutubeJavaScriptPlayerManager.deobfuscateSignature(id, s)
            }
            if (client.needsJsPlayer || Uri.parse(url).getQueryParameter("n") != null) {
                url = runCatching {
                    YoutubeJavaScriptPlayerManager.getUrlWithThrottlingParameterDeobfuscated(id, url)
                }.getOrDefault(url)
            }
            return url
        }
    }
