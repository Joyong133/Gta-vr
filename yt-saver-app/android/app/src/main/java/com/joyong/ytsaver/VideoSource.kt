/** 받을 수 있는 스트림 하나 (영상만 / 영상+소리 / 소리만) */
data class MediaStream(
    val url: String,
    val kind: Kind,
    /** 저장할 파일 확장자: mp4, webm, m4a */
    val ext: String,
    val codec: String,
    val height: Int,
    val bitrate: Int,
    val contentLength: Long,
    /** 더빙이 아닌 원래 소리 트랙인지 */
    val originalAudio: Boolean = true,
) {
    enum class Kind { VIDEO_ONLY, MUXED, AUDIO }

    val isAvc get() = ext == "mp4" && codec.startsWith("avc1")
    val isAv1 get() = codec.startsWith("av01")
}

/** 기본 방식이 막힌 뒤 대체 클라이언트까지 모두 실패 */
class AllClientsFailedException(
    /** 처음(기본 방식) 실패 원인 */
    cause: Throwable,
    /** 대체 클라이언트별 결과 한 줄씩 */
    val attempts: List<String>,
) : Exception(cause.message, cause)

data class Caption(val url: String, val languageTag: String, val isAutoGenerated: Boolean)

/** 어느 방식으로 가져왔든 같은 모양으로 다루기 위한 영상 정보 */
data class VideoInfo(
    val id: String,
    val title: String,
    val uploader: String,
    val durationSec: Long,
    val thumbnailUrl: String?,
    val streams: List<MediaStream>,
    val captions: List<Caption>,
    /** 스트림을 받을 때 써야 하는 User-Agent (요청한 클라이언트와 같아야 함) */
    val userAgent: String,
    /** 어느 클라이언트로 받았는지 (오류 안내용) */
    val via: String,
)

/**
 * 영상 정보 가져오기.
 * 1) NewPipeExtractor 기본 방식(VisionOS 클라이언트)
 * 2) 유튜브가 그 방식을 "로봇 확인"으로 막으면 다른 클라이언트(TV, Oculus VR)로 직접 요청
 *    (yt-dlp가 쓰는 클라이언트 설정을 참고)
 */
object VideoSource {

    fun fetch(id: String): VideoInfo {
        val first = try {
            return fromNewPipe(StreamInfo.getInfo(ServiceList.YouTube, watchUrl(id)), id)
        } catch (e: SignInConfirmNotBotException) {
            e
        }
        val attempts = mutableListOf<String>()
        for (client in FALLBACK_CLIENTS) {
            try {
                return Innertube.player(id, client)
            } catch (e: Exception) {
                attempts += "${client.label} → ${e.javaClass.simpleName}: ${e.message}"
            }
        }
        throw AllClientsFailedException(first, attempts)
    }

    private fun watchUrl(id: String) = "https://www.youtube.com/watch?v=$id"

    private fun fromNewPipe(info: StreamInfo, id: String): VideoInfo {
        fun Stream.usable() = isUrl && deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP
        val streams = buildList {
            info.videoOnlyStreams.filter { it.usable() }.forEach {
                add(
                    MediaStream(
                        it.content, MediaStream.Kind.VIDEO_ONLY, it.format?.suffix ?: "mp4",
                        it.codec.orEmpty(), it.height, it.bitrate, it.itagItem?.contentLength ?: -1
                    )
                )
            }
            info.videoStreams.filter { it.usable() }.forEach {
                add(
                    MediaStream(
                        it.content, MediaStream.Kind.MUXED, it.format?.suffix ?: "mp4",
                        it.codec.orEmpty(), it.height, it.bitrate, it.itagItem?.contentLength ?: -1
                    )
                )
            }
            info.audioStreams.filter { it.usable() }.forEach {
                add(
                    MediaStream(
                        it.content, MediaStream.Kind.AUDIO,
                        if (it.format == MediaFormat.M4A) "m4a" else it.format?.suffix ?: "m4a",
                        it.codec.orEmpty(), 0, it.averageBitrate, it.itagItem?.contentLength ?: -1,
                        originalAudio = it.audioTrackType == null || it.audioTrackType == AudioTrackType.ORIGINAL,
                    )
                )
            }
        }
        return VideoInfo(
            id = id,
            title = info.name ?: id,
            uploader = info.uploaderName.orEmpty(),
            durationSec = info.duration,
            thumbnailUrl = info.thumbnails.minByOrNull { kotlin.math.abs(it.width - 480) }?.url,
            streams = streams,
            captions = info.subtitles.map { Caption(it.content, it.languageTag, it.isAutoGenerated) },
            userAgent = YoutubeParsingHelper.getVisionOsUserAgent(null),
            via = "VisionOS",
        )
    }

