package com.joyong.ytsaver

import kotlinx.coroutines.delay
import kotlinx.coroutines.ensureActive
import okhttp3.FormBody
import okhttp3.Request
import org.json.JSONArray
import java.io.IOException
import kotlin.coroutines.coroutineContext

/**
 * 구글 번역(웹 번역기와 같은 무료 엔드포인트)으로 자막을 한국어로 번역한다.
 * API 키가 필요 없고 기기 번역(ML Kit)보다 품질이 좋다.
 * 공식 유료 API가 아니라서 너무 많이 요청하면 잠시 막힐 수 있다.
 */
object GoogleTranslator {

    private const val URL = "https://translate.googleapis.com/translate_a/single"
    private const val MAX_CHARS = 4500

    suspend fun translate(
        cues: List<SubtitleSaver.Cue>,
        sourceLang: String,
        autoGenerated: Boolean,
        onStatus: (String) -> Unit,
    ): List<SubtitleSaver.Cue> {
        // 자동 생성 자막은 문장이 여러 줄로 쪼개져 있어 줄 단위로 번역하면 어색하다 → 문장 단위로 합친다
        val units = if (autoGenerated) mergeIntoSentences(cues) else cues
        val sl = sourceLang.substringBefore('-').lowercase().ifEmpty { "auto" }
        val out = ArrayList<SubtitleSaver.Cue>(units.size)
        var i = 0
        while (i < units.size) {
            coroutineContext.ensureActive()
            onStatus("구글 번역 중… ${i * 100 / units.size}%")
            // 줄바꿈으로 이어 붙여 한 번에 보내고, 결과를 다시 줄바꿈으로 나눈다
            var end = i
            var chars = 0
            while (end < units.size && (end == i || chars + units[end].text.length + 1 <= MAX_CHARS)) {
                chars += units[end].text.length + 1
                end++
            }
            val chunk = units.subList(i, end)
            val lines = chunk.map { it.text.replace('\n', ' ') }
            var translated = request(lines.joinToString("\n"), sl).split('\n')
            if (translated.size != lines.size) {
                // 줄 수가 어긋나면 한 줄씩 다시 (느리지만 정확)
                translated = lines.map { line ->
                    coroutineContext.ensureActive()
                    delay(150)
                    request(line, sl).replace('\n', ' ')
                }
            }
            chunk.forEachIndexed { k, cue ->
                out += cue.copy(text = translated[k].trim().ifEmpty { cue.text })
            }
            i = end
            delay(300)
        }
        return out
    }

    /** 짧은 문장 하나 번역 (검색어 번역용). sl=auto면 언어 자동 감지 */
    fun translateText(text: String, targetLang: String, sourceLang: String = "auto"): String =
        request(text, sourceLang, targetLang).trim()

    /** 문장의 언어 코드 감지 (ko, en, ja …). 실패하면 null */
    fun detectLanguage(text: String): String? = runCatching {
        val url = "$URL?client=gtx&sl=auto&tl=en&dt=t"
        val request = Request.Builder()
            .url(url)
            .post(FormBody.Builder().add("q", text).build())
            .header("User-Agent", NetDownloader.USER_AGENT)
            .build()
        App.http.newCall(request).execute().use { resp ->
            if (!resp.isSuccessful) return@runCatching null
            JSONArray(resp.body?.string().orEmpty()).optString(2).takeIf { it.isNotEmpty() }
        }
    }.getOrNull()

    private fun request(text: String, sourceLang: String, targetLang: String = "ko"): String {
        val url = "$URL?client=gtx&sl=$sourceLang&tl=$targetLang&dt=t"
        val request = Request.Builder()
            .url(url)
            .post(FormBody.Builder().add("q", text).build())
            .header("User-Agent", NetDownloader.USER_AGENT)
            .build()
        val body = App.http.newCall(request).execute().use { resp ->
            if (resp.code == 429) throw IOException("구글 번역이 잠시 요청을 막았어요")
            if (!resp.isSuccessful) throw IOException("구글 번역 HTTP ${resp.code}")
            resp.body?.string().orEmpty()
        }
        // [[["번역문","원문",...], ...], null, "en", ...]
        val segments = runCatching { JSONArray(body).getJSONArray(0) }.getOrNull()
            ?: throw IOException("구글 번역 응답을 읽지 못했어요")
        return buildString {
            for (s in 0 until segments.length()) {
                append(segments.optJSONArray(s)?.optString(0).orEmpty())
            }
        }
    }

    /**
     * 문장 끝(. ? ! 등)이 나오거나 충분히 길어질 때까지 이어지는 줄을 하나로 합친다.
     * 합친 자막은 첫 줄 시작부터 마지막 줄 끝까지 보인다.
     */
    private fun mergeIntoSentences(cues: List<SubtitleSaver.Cue>): List<SubtitleSaver.Cue> {
        val enders = setOf('.', '?', '!', '。', '？', '！', '…')
        val merged = ArrayList<SubtitleSaver.Cue>()
        var group = ArrayList<SubtitleSaver.Cue>()
        fun flush() {
            if (group.isEmpty()) return
            merged += SubtitleSaver.Cue(
                group.first().startMs, group.last().endMs,
                group.joinToString(" ") { it.text.trim() }
            )
            group = ArrayList()
        }
        for (cue in cues) {
            val prev = group.lastOrNull()
            // 말이 2초 넘게 끊기면 새 문장으로
            if (prev != null && cue.startMs - prev.endMs > 2000) flush()
            group += cue
            val length = group.sumOf { it.text.length }
            val duration = group.last().endMs - group.first().startMs
            if (cue.text.trim().lastOrNull() in enders || length >= 90 || duration >= 7000) flush()
        }
        flush()
        return merged
    }
}
